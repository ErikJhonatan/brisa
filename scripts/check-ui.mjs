import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('test-results', { recursive: true });
await page.goto('http://localhost:5174');
await page.getByRole('heading', { name: 'Baja el ritmo.' }).waitFor();
await page.waitForTimeout(900);
await page.screenshot({ path: 'test-results/home-mobile.png', fullPage: true });
for (const width of [320, 390, 768, 1280]) {
  await page.setViewportSize({ width, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Horizontal overflow at ${width}px`);
}
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('button', { name: 'Prácticas', exact: true }).click();
await page.getByRole('button', { name: 'Descanso', exact: true }).click();
assert.equal(await page.locator('.practice-card').count(), 2);
await page.getByRole('button', { name: 'Todas', exact: true }).click();
assert.equal(await page.locator('.practice-card').count(), 9);
await page.waitForTimeout(400);
await page.screenshot({ path: 'test-results/practices-mobile.png', fullPage: true });
await page.getByRole('button', { name: /Suspiro cíclico Un suspiro de calma/ }).click();
await page.getByRole('dialog').waitFor();
await page.locator('.checkin').getByRole('button', {name:'6',exact:true}).click();
await page.screenshot({ path: 'test-results/preparation-mobile.png', fullPage: true });
await page.getByRole('button', { name: 'Comenzar mi pausa' }).click();
await page.getByRole('button',{name:'Saltar introducción y comenzar'}).click();
await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
await page.waitForTimeout(1200);
await page.screenshot({ path: 'test-results/session-mobile.png', fullPage: true });
await page.getByRole('button', { name: 'Pausar', exact: true }).click();
const value = await page.getByRole('progressbar').getAttribute('aria-valuenow');
await page.waitForTimeout(1200);
assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'), value);
await page.clock.install();
await page.getByRole('button', { name: 'Continuar', exact: true }).click();
await page.clock.fastForward(61_000);
await page.clock.resume();
await page.getByRole('heading', { name: /Gracias por/ }).waitFor();
await page.getByRole('button', { name: 'Más tranquilo/a' }).click();
await page.locator('.checkin').getByRole('button', {name:'2',exact:true}).click();
await page.getByRole('button', { name: 'Volver al inicio' }).click();
await page.getByRole('button', { name: 'Mi espacio', exact: true }).click();
assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('brisa-history')).length), 1);
assert.deepEqual(await page.evaluate(() => {const e=JSON.parse(localStorage.getItem('brisa-history'))[0];return [e.before,e.after];}),[6,2]);
await page.getByRole('button', { name: 'Cerrar panel' }).click();
await page.reload();
await page.getByRole('button', { name: 'Mi espacio', exact: true }).click();
await page.getByText('pausas completadas').waitFor();
await page.getByRole('button', { name: 'Cerrar panel' }).click();
await page.getByRole('dialog').waitFor({ state: 'hidden' });
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.getByRole('button', { name: 'Abrir ajustes' }).click();
assert.equal(await page.getByRole('switch', { name: 'Menos movimiento' }).isChecked(), true);
await page.getByRole('button', { name: 'Cerrar panel' }).click();
assert.deepEqual(errors, []);
await browser.close();
console.log('UI OK: 320/390/768/1280px, filters, drawer, timer, pause, completion, persistence, reduced motion; no runtime errors.');
