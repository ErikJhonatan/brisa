import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless:true });
const page = await browser.newPage({ viewport:{width:390,height:844}, isMobile:true });
page.setDefaultTimeout(10000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.addInitScript(() => { const NativeAudio = window.Audio; window.__players = []; window.Audio = class extends NativeAudio { constructor(...args) { super(...args); window.__players.push(this); } }; });
await page.goto(process.env.BRISA_URL || 'http://localhost:5174');
await page.getByRole('button', {name:'Abrir ajustes'}).click();
await page.getByRole('button', {name:/Chills Chillhop/}).click();
await page.getByRole('button', {name:'Escuchar muestra'}).click();
await page.waitForTimeout(1500);
assert.equal(await page.evaluate(() => window.__players.some(p => p.src.endsWith('/audio/chills.mp3') && !p.paused && p.currentTime > 0)), true, 'CC0 recording must actually play');
await page.getByRole('button', {name:'Detener muestra'}).click();
assert.equal(await page.evaluate(() => window.__players.every(p => p.paused)), true);
await page.getByRole('switch', {name:'Sonido de respiración', exact:true}).check();
await page.getByRole('slider', {name:'Volumen de música', exact:true}).fill('0.25');
await page.getByRole('slider', {name:'Volumen de respiración', exact:true}).fill('0.5');
await page.locator('summary').filter({hasText:'Guía de voz'}).click();
assert.equal(await page.locator('input[type=file]').count(),0,'The app must not offer audio uploads');
await page.getByText('Leer introducción',{exact:true}).click();
await page.getByText(/Busca una postura cómoda. No hay nada que demostrar/).waitFor();
const geometry = await page.locator('.drawer-scroll').evaluate(el => { el.scrollTop = el.scrollHeight; const last = el.lastElementChild.getBoundingClientRect(); const bounds = el.getBoundingClientRect(); return {gap:bounds.bottom-last.bottom, height:el.clientHeight, scroll:el.scrollHeight, pseudo:getComputedStyle(el.parentElement,'::after').display}; });
assert.equal(geometry.pseudo, 'none'); assert.ok(geometry.gap < 40, `Blank scroll gap ${geometry.gap}`);
await page.screenshot({path:'test-results/settings-audio-mobile.png'});
await page.getByRole('button', {name:'Cerrar panel'}).click(); await page.getByRole('dialog').waitFor({state:'hidden'});
assert.equal(await page.evaluate(() => window.__players.every(p => p.paused)), true);
await page.reload();
assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('brisa-settings')).audio.track), 'chills');
await page.getByRole('button', {name:'Prácticas', exact:true}).click();
await page.getByRole('button', {name:/Respiración en caja Encuentra tu centro/}).click();
await page.getByRole('button', {name:'Guardar práctica', exact:true}).click();
await page.getByRole('switch', {name:'Omitir retenciones'}).check();
await page.locator('.checkin').getByRole('button', {name:'6',exact:true}).click();
await page.getByRole('button', {name:'Comenzar mi pausa'}).click();
await page.getByRole('button',{name:'Saltar introducción y comenzar'}).click();
await page.getByRole('button', {name:'Pausar', exact:true}).waitFor();
await page.waitForTimeout(1200);
assert.ok(await page.evaluate(() => window.__players.some(p => !p.paused)), 'Music resumes inside session');
await page.getByRole('button', {name:'Pausar',exact:true}).click();
await page.waitForTimeout(100);
assert.equal(await page.evaluate(() => window.__players.every(p => p.paused)), true);
await page.getByRole('button', {name:/Esto me incomoda/}).click();
await page.getByRole('heading', {name:'Aquí y ahora',exact:true}).waitFor();
await page.getByRole('button', {name:'Cerrar panel'}).click(); await page.getByRole('dialog').waitFor({state:'hidden'});
await page.getByRole('button', {name:'Terminar por ahora'}).click();
await page.getByRole('button', {name:'Prácticas',exact:true}).click();
await page.getByRole('button', {name:'Favoritas',exact:true}).click();
assert.equal(await page.locator('.practice-card').count(),1);
await page.getByRole('button', {name:'Mi espacio',exact:true}).click();
await page.locator('summary').filter({hasText:'Recordar mi pausa'}).click();
await page.getByRole('switch', {name:'Activar recordatorio'}).check();
await page.getByLabel('Hora del recordatorio').fill('21:15');
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button', {name:'Añadir recordatorio diario al calendario'}).click();
assert.equal((await downloadPromise).suggestedFilename(),'mi-pausa-brisa.ics');
await page.getByRole('button', {name:'Borrar mis datos',exact:true}).click();
await page.getByRole('button', {name:'Sí, borrar datos',exact:true}).click();
await page.waitForTimeout(200);
assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('brisa-settings')).favorites.length),0);
assert.deepEqual(errors, []);
await browser.close();
console.log('Feature checks OK: real MP3 playback, independent volumes, fixed voice scripts without upload controls, pause/stop, drawer scroll geometry, favorites, retention-free mode, grounding, calendar export, data deletion.');
